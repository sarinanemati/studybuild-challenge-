import pandas as pd

df = pd.read_excel("studybuild-challenge.xlsx", sheet_name="Messy_Data")
df.columns = df.columns.str.strip()

df["Age"] = pd.to_numeric(df["Age"], errors="coerce")
df.loc[~df["Age"].between(1, 120), "Age"] = pd.NA

amount = (
    df["Purchase_Amount"].astype("string").str.strip()
    .str.replace(",", "", regex=False)
    .str.replace(r"(?i)^(\d+(?:\.\d+)?)k$", lambda m: str(float(m.group(1)) * 1000), regex=True)
)
df["Purchase_Amount"] = pd.to_numeric(amount, errors="coerce")
df.loc[df["Purchase_Amount"] <= 0, "Purchase_Amount"] = pd.NA

df["Discount"] = pd.to_numeric(df["Discount"], errors="coerce")
df.loc[~df["Discount"].between(0, 1), "Discount"] = pd.NA

for col in ["City", "Category", "Returned"]:
    df[col] = df[col].astype("string").str.strip()

df["City"] = df["City"].str.title().replace({
    "Mashad": "Mashhad"
})

df["Category"] = df["Category"].str.title()

df.loc[
    ~df["Returned"].isin(["Yes", "No"]),
    "Returned"
] = pd.NA

df["Email"] = df["Email"].astype("string")

email_pattern = r"^[\w\.-]+@[\w\.-]+\.\w+$"

df.loc[
    ~df["Email"].str.match(email_pattern, na=False),
    "Email"
] = pd.NA

df["Order_Date"] = pd.to_datetime(
    df["Order_Date"],
    errors="coerce",
    format="mixed"
)

df = df.drop_duplicates()

assert df["Age"].dropna().between(1, 120).all(), "ایراد در ستون سن!"
assert df["Discount"].dropna().between(0, 1).all(), "ایراد در ستون تخفیف!"
assert df["Purchase_Amount"].dropna().gt(0).all(), "ایراد در ستون مبلغ خرید!"
assert df["Returned"].dropna().isin(["Yes", "No"]).all(), "ایراد در ستون مرجوعی!"

test_summary = pd.DataFrame({
    "dtype": df.dtypes.astype(str),
    "missing_values": df.isna().sum(),
    "unique_values": df.nunique()
})

print(test_summary)
print("\n everything was checked")

